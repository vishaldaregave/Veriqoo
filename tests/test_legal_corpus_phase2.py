    def test_loader_uses_bigint_identity_mappings_and_is_idempotent(self):
        state = {"documents": [], "provisions": [], "phase2": {}}
        next_ids = {"document": 1, "provision": 1}

        class Response:
            def __init__(self, rows=None, status_code=201):
                self._rows = rows or []
                self.status_code = status_code
                self.text = ""
                self.ok = True
                self.content = b"body" if rows else b""

            def json(self):
                return self._rows

        def fake_get(url, **kwargs):
            table = url.rsplit("/", 1)[-1]
            params = kwargs.get("params", {})
            if table == "legal_documents":
                rows = [row for row in state["documents"] if row["source_hash"] == params["source_hash"].removeprefix("eq.")]
                return Response(rows)
            if table == "legal_provisions":
                target_id = int(params["document_id"].removeprefix("eq."))
                rows = [row for row in state["provisions"] if row["document_id"] == target_id]
                range_start = int(kwargs.get("headers", {}).get("Range", "0-999").split("-")[0])
                return Response(rows[range_start:range_start + 1000])
            raise AssertionError(f"Unexpected GET table: {table}")

        def fake_post(url, **kwargs):
            table = url.rsplit("/", 1)[-1]
            payload = kwargs["json"]
            if table == "legal_documents":
                row = {**payload, "id": next_ids["document"]}
                next_ids["document"] += 1
                state["documents"].append(row)
                return Response([{"id": row["id"], "source_hash": row["source_hash"]}])
            if table == "legal_provisions":
                created = []
                for payload_row in payload:
                    row = {**payload_row, "id": next_ids["provision"]}
                    next_ids["provision"] += 1
                    state["provisions"].append(row)
                    created.append({"id": row["id"], "source_location": row["source_location"]})
                return Response(created)
            for row in payload:
                state["phase2"].setdefault(table, {})[row["source_identifier"]] = row
            return Response(status_code=204)

        with patch("requests.get", side_effect=fake_get), patch("requests.post", side_effect=fake_post):
            first = load_groups_to_supabase("https://mock.invalid", "offline-test-key", self.corpus, batch_size=1000)
            first_sizes = (len(state["documents"]), len(state["provisions"]))
            second = load_groups_to_supabase("https://mock.invalid", "offline-test-key", self.corpus, batch_size=1000)

        self.assertEqual(first, second)
        self.assertEqual((1, len(self.corpus.provisions)), first_sizes)
        self.assertEqual(1, len(state["documents"]))
        self.assertEqual(len(self.corpus.provisions), len(state["provisions"]))
        self.assertEqual(
            {table: len(rows) for table, rows in ordered_load_groups(self.corpus) if table not in {"legal_documents", "legal_provisions"}},
            {table: len(rows) for table, rows in state["phase2"].items()},
        )

