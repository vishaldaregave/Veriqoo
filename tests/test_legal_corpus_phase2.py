def migration_table_body(migration: str, table: str) -> str:
    match = re.search(
        rf"CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+public\.{table}\s*\((.*?)\n\);",
        migration,
        re.I | re.S,
    )
    if match is None:
        raise AssertionError(f"Table definition not found: {table}")
    return match.group(1)


def phase1_column_inventory(migration: str, table: str) -> dict[str, dict[str, object]]:
    inventory: dict[str, dict[str, object]] = {}
    for line in migration_table_body(migration, table).splitlines():
        line = line.strip().rstrip(",")
        column_match = re.match(r"\s*(\w+)\s+(bigint|text|timestamptz)\b(.*)", line, re.I)
        if column_match is None:
            continue
        name, data_type, attributes = column_match.groups()
        identity_match = re.search(r"GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY", attributes, re.I)
        default_match = re.search(r"\bDEFAULT\s+(.+?)(?:\s+PRIMARY\s+KEY)?$", attributes, re.I)
        reference_match = re.search(r"\bREFERENCES\s+public\.(\w+)\((\w+)\)", attributes, re.I)
        is_primary_key = bool(re.search(r"\bPRIMARY\s+KEY\b", attributes, re.I))
        inventory[name] = {
            "type": data_type.lower(),
            "nullable": not bool(re.search(r"\bNOT\s+NULL\b", attributes, re.I) or is_primary_key),
            "default": "GENERATED BY DEFAULT AS IDENTITY" if identity_match else (default_match.group(1) if default_match else None),
            "primary_key": is_primary_key,
            "foreign_key": f"{reference_match.group(1)}({reference_match.group(2)})" if reference_match else None,
        }
    return inventory


