from __future__ import annotations

import re
import unittest
from pathlib import Path

from backend.app.services.applicability_vocabulary import (
    ACTOR_ROLES,
    APPLICABILITY_RESULTS,
    CONDITION_GROUP_OPERATORS,
    CONDITION_OPERATORS,
    CONSUMER_TYPES,
    FACT_KEYS,
    FACT_STATUSES,
    QUANTITY_DIMENSIONS,
    RULE_VERSION_STATUSES,
    SALE_CONTEXTS,
    SOURCE_ROLES,
)


ROOT = Path(__file__).resolve().parents[1]
MIGRATION = ROOT / "supabase" / "migrations" / "20261002000002_phase3a_applicability.sql"
PHASE1_MIGRATION = ROOT / "supabase" / "migrations" / "20261002000000_legal_corpus_hierarchy.sql"
PHASE2_MIGRATION = ROOT / "supabase" / "migrations" / "20261002000001_legal_corpus_phase2.sql"
EXPECTED_TABLES = {
    "applicability_rules",
    "applicability_rule_versions",
    "applicability_condition_groups",
    "applicability_conditions",
    "applicability_rule_sources",
    "applicability_runs",
    "inspection_facts",
    "applicability_decisions",
    "applicability_decision_evidence",
}


def table_body(sql: str, table: str) -> str:
    match = re.search(
        rf"CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+public\.{table}\s*\((.*?)\n\);",
        sql,
        re.I | re.S,
    )
    if match is None:
        raise AssertionError(f"Table definition not found: {table}")
    return match.group(1)


class Phase3ASchemaTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.sql = MIGRATION.read_text(encoding="utf-8")

    def test_exactly_nine_approved_tables_and_no_forbidden_tables(self):
        created = set(re.findall(r"CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+public\.(\w+)", self.sql, re.I))
        self.assertEqual(EXPECTED_TABLES, created)
        forbidden = {
            "applicability_exceptions",
            "applicability_required_facts",
            "applicability_rule_schedules",
            "fact_definitions",
            "rule_dependencies",
            "applicability_facts",
        }
        self.assertFalse(created & forbidden)

    def test_existing_legal_corpus_tables_are_referenced_not_recreated(self):
        for table in (
            "legal_documents",
            "legal_provisions",
            "legal_requirements",
            "legal_schedules",
            "legal_schedule_entries",
            "legal_tables",
            "legal_amendments",
        ):
            self.assertNotRegex(self.sql, rf"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?public\.{table}\b")
        self.assertIn("legal_requirements(id)", self.sql)
        self.assertIn("legal_provisions(id)", self.sql)

    def test_existing_corpus_foreign_key_types_are_respected(self):
        expected = (
            ("applicability_rule_sources", "requirement_id", "uuid", "legal_requirements"),
            ("applicability_rule_sources", "provision_id", "bigint", "legal_provisions"),
            ("applicability_rule_sources", "schedule_id", "uuid", "legal_schedules"),
            ("applicability_rule_sources", "schedule_entry_id", "uuid", "legal_schedule_entries"),
            ("applicability_rule_sources", "table_id", "uuid", "legal_tables"),
            ("applicability_rule_sources", "amendment_id", "uuid", "legal_amendments"),
        )
        for source_table, column, data_type, target in expected:
            with self.subTest(source_table=source_table, column=column):
                body = table_body(self.sql, source_table)
                self.assertRegex(body, rf"\b{column}\s+{data_type}\b[^\n]*REFERENCES\s+public\.{target}\(id\)")

    def test_phase1_and_phase2_migration_definitions_are_untouched_by_this_schema(self):
        phase1 = PHASE1_MIGRATION.read_text(encoding="utf-8")
        phase2 = PHASE2_MIGRATION.read_text(encoding="utf-8")
        self.assertIn("id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", phase1)
        for table in ("legal_documents", "legal_provisions"):
            self.assertNotRegex(phase2, rf"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?public\.{table}\b")
            self.assertNotRegex(phase2, rf"ALTER\s+TABLE\s+public\.{table}\b")
        self.assertNotRegex(self.sql, r"ALTER\s+TABLE\s+public\.(?:legal_documents|legal_provisions|legal_requirements|legal_schedules|legal_schedule_entries|legal_tables|legal_amendments)\b")

    def test_condition_operator_and_nested_group_constraints(self):
        condition = table_body(self.sql, "applicability_conditions")
        groups = table_body(self.sql, "applicability_condition_groups")
        for operator in CONDITION_OPERATORS:
            self.assertIn(f"'{operator}'", condition)
        self.assertIn("boolean_operator IN ('AND', 'OR')", groups)
        self.assertRegex(groups, r"parent_group_id\s+uuid\s+REFERENCES\s+public\.applicability_condition_groups\(id\)")
        self.assertIn("group_purpose IN ('applicability', 'exception')", groups)

    def test_source_role_checks_require_matching_source_links(self):
        source = table_body(self.sql, "applicability_rule_sources")
        for role in SOURCE_ROLES:
            self.assertIn(f"'{role}'", source)
        self.assertIn("source_role = 'condition' AND (condition_group_id IS NOT NULL OR condition_id IS NOT NULL)", source)
        self.assertIn("source_role = 'exception' AND condition_group_id IS NOT NULL", source)
        self.assertIn("source_role = 'schedule_scope' AND (schedule_id IS NOT NULL OR schedule_entry_id IS NOT NULL OR table_id IS NOT NULL)", source)
        self.assertIn("source_role = 'amends' AND amendment_id IS NOT NULL", source)

    def test_fact_statuses_known_value_and_nonknown_null_constraints(self):
        facts = table_body(self.sql, "inspection_facts")
        for status in FACT_STATUSES:
            self.assertIn(f"'{status}'", facts)
        self.assertIn("fact_status = 'known' AND value IS NOT NULL", facts)
        self.assertIn("fact_status <> 'known' AND value IS NULL", facts)

    def test_decision_result_enum_is_exact_and_approval_gate_is_service_owned(self):
        decisions = table_body(self.sql, "applicability_decisions")
        self.assertIn("result IN ('applicable', 'not_applicable', 'unknown')", decisions)
        versions = table_body(self.sql, "applicability_rule_versions")
        for status in RULE_VERSION_STATUSES:
            self.assertIn(f"'{status}'", versions)
        self.assertIn("UNIQUE (run_id, rule_version_id)", decisions)
        self.assertIn("engine/service must reject every version whose interpretation_status is not approved", self.sql)
        self.assertNotRegex(self.sql, r"CHECK\s*\([\s\S]{0,400}SELECT[\s\S]{0,200}interpretation_status")

    def test_rule_version_uniqueness_and_temporal_columns(self):
        versions = table_body(self.sql, "applicability_rule_versions")
        self.assertIn("UNIQUE (rule_id, version_number)", versions)
        self.assertRegex(versions, r"valid_from\s+date")
        self.assertRegex(versions, r"valid_to\s+date")
        self.assertRegex(versions, r"amendment_id\s+uuid\s+REFERENCES\s+public\.legal_amendments\(id\)")

    def test_decision_evidence_links_are_explainable(self):
        evidence = table_body(self.sql, "applicability_decision_evidence")
        self.assertIn("condition_id uuid REFERENCES public.applicability_conditions(id)", evidence)
        self.assertIn("fact_id uuid REFERENCES public.inspection_facts(id)", evidence)
        self.assertIn("source_link_id uuid REFERENCES public.applicability_rule_sources(id)", evidence)
        self.assertIn("evaluation IN ('true', 'false', 'unknown', 'not_evaluated')", evidence)

    def test_fact_vocabulary_has_no_inspection_date_or_other_consumer(self):
        self.assertEqual(
            {
                "is_prepackaged", "commodity", "quantity", "quantity_unit", "actor_role",
                "sale_context", "consumer_type", "observed_declarations",
            },
            FACT_KEYS,
        )
        self.assertEqual({"institutional", "industrial"}, CONSUMER_TYPES)
        self.assertEqual({"retail", "wholesale", "export", "domestic"}, SALE_CONTEXTS)
        self.assertTrue({"manufacturer", "packer", "importer", "dealer", "retail_dealer", "wholesale_dealer"} == ACTOR_ROLES)
        self.assertEqual({"weight", "volume", "length", "area", "number"}, QUANTITY_DIMENSIONS)
        self.assertNotIn("inspection_date", FACT_KEYS)
        self.assertNotIn("other", CONSUMER_TYPES)

    def test_no_destructive_sql_and_rerunnable_table_indexes(self):
        self.assertNotRegex(self.sql, re.compile(r"\bDROP\s+TABLE\b", re.I))
        self.assertNotRegex(self.sql, re.compile(r"\bDROP\s+COLUMN\b", re.I))
        self.assertNotRegex(self.sql, re.compile(r"\bTRUNCATE\b", re.I))
        self.assertNotRegex(self.sql, re.compile(r"\bDELETE\s+FROM\b", re.I))
        self.assertNotRegex(self.sql, re.compile(r"\bALTER\s+TABLE\b", re.I))
        self.assertNotRegex(self.sql, re.compile(r"\bON\s+DELETE\s+(?:CASCADE|SET\s+NULL)\b", re.I))
        self.assertEqual(9, self.sql.upper().count("CREATE TABLE IF NOT EXISTS"))
        self.assertTrue(all(line.startswith("CREATE INDEX IF NOT EXISTS") for line in self.sql.splitlines() if line.startswith("CREATE INDEX")))


if __name__ == "__main__":
    unittest.main()
