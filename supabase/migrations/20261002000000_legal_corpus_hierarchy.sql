CREATE TABLE IF NOT EXISTS public.legal_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL,
    document_title text,
    document_version text,
    source_pdf_path text,
    source_hash text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.legal_provisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES public.legal_documents(id),
    parent_provision_id bigint NULL REFERENCES public.legal_provisions(id),
    provision_type text NOT NULL CHECK (
        provision_type IN (
            'document',
            'rule',
            'sub_rule',
            'clause',
            'proviso',
            'explanation',
            'schedule',
            'table',
            'amendment'
        )
    ),
    rule_number text,
    sub_rule_number text,
    clause text,
    schedule_number text,
    title text,
    content text,
    raw_content text,
    source_location text,
    source text NOT NULL DEFAULT 'pdf',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_legal_provisions_document_id
    ON public.legal_provisions(document_id);

CREATE INDEX IF NOT EXISTS idx_legal_provisions_parent_provision_id
    ON public.legal_provisions(parent_provision_id);

CREATE INDEX IF NOT EXISTS idx_legal_provisions_rule_number
    ON public.legal_provisions(rule_number);

CREATE INDEX IF NOT EXISTS idx_legal_provisions_schedule_number
    ON public.legal_provisions(schedule_number);

CREATE OR REPLACE FUNCTION public.touch_legal_provisions_updated_at()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_touch_legal_provisions_updated_at ON public.legal_provisions;
CREATE TRIGGER trg_touch_legal_provisions_updated_at
BEFORE UPDATE ON public.legal_provisions
FOR EACH ROW
EXECUTE FUNCTION public.touch_legal_provisions_updated_at();

DROP TRIGGER IF EXISTS trg_touch_legal_documents_updated_at ON public.legal_documents;
CREATE TRIGGER trg_touch_legal_documents_updated_at
BEFORE UPDATE ON public.legal_documents
FOR EACH ROW
EXECUTE FUNCTION public.touch_legal_provisions_updated_at();
